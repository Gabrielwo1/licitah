    <div >
        <h2>1. Dados que Coletamos</h2>
        <p>Coletamos informações pessoais fornecidas diretamente pelos usuários e dados gerados automaticamente pelo uso de nossos serviços, tais como:</p>
        <ul>
            <li><strong>Dados Pessoais:</strong> Nome, endereço, e-mail, telefone, CPF, entre outros.</li>
            <li><strong>Dados de Navegação:</strong> Endereço IP, tipo de navegador, páginas acessadas, tempo de permanência, entre outros.</li>
            <li><strong>Dados de Transações:</strong> Histórico de compras, métodos de pagamento, entre outros.</li>
        </ul>
    </div>

    <div >
        <h2>2. Finalidade do Tratamento de Dados</h2>
        <p>Utilizamos os dados pessoais coletados para as seguintes finalidades:</p>
        <ul>
            <li><strong>Prestação de Serviços:</strong> Para fornecer e gerenciar os serviços solicitados pelos usuários.</li>
            <li><strong>Comunicação:</strong> Para enviar notificações, atualizações e ofertas, conforme autorizado pelos usuários.</li>
            <li><strong>Melhoria dos Serviços:</strong> Para entender melhor o comportamento dos usuários e otimizar nossos serviços.</li>
            <li><strong>Cumprimento Legal:</strong> Para atender a obrigações legais e regulatórias.</li>
        </ul>
    </div>

    <div >
        <h2>3. Compartilhamento de Dados</h2>
        <p>Os dados pessoais dos usuários podem ser compartilhados com terceiros nas seguintes situações:</p>
        <ul>
            <li><strong>Parceiros de Negócios:</strong> Com fornecedores e prestadores de serviços que auxiliam na operação dos nossos serviços.</li>
            <li><strong>Autoridades Legais:</strong> Para cumprimento de obrigações legais ou para responder a processos judiciais.</li>
            <li><strong>Transferências de Negócios:</strong> Em caso de fusão, aquisição ou venda de ativos, os dados poderão ser transferidos para a nova entidade.</li>
        </ul>
    </div>

    <div >
        <h2>4. Armazenamento e Segurança dos Dados</h2>
        <p>Implementamos medidas técnicas e organizacionais adequadas para proteger os dados pessoais contra acesso não autorizado, perda, destruição ou alteração. Os dados são armazenados pelo período necessário para cumprir as finalidades para as quais foram coletados ou conforme exigido por lei.</p>
    </div>

    <div >
        <h2>5. Direitos dos Titulares de Dados</h2>
        <p>Em conformidade com a LGPD, os titulares de dados têm os seguintes direitos:</p>
        <ul>
            <li><strong>Acesso:</strong> Direito de solicitar o acesso aos dados pessoais que possuímos.</li>
            <li><strong>Correção:</strong> Direito de solicitar a correção de dados incompletos, inexatos ou desatualizados.</li>
            <li><strong>Anonimização, Bloqueio ou Eliminação:</strong> Direito de solicitar a anonimização, bloqueio ou eliminação de dados desnecessários, excessivos ou tratados em desconformidade com a LGPD.</li>
            <li><strong>Portabilidade:</strong> Direito de solicitar a portabilidade dos dados para outro fornecedor de serviço ou produto.</li>
            <li><strong>Eliminação:</strong> Direito de solicitar a eliminação dos dados pessoais tratados com o consentimento do titular.</li>
            <li><strong>Informação:</strong> Direito de ser informado sobre as entidades públicas e privadas com as quais os dados foram compartilhados.</li>
            <li><strong>Revogação do Consentimento:</strong> Direito de revogar o consentimento a qualquer momento, mediante manifestação expressa.</li>
        </ul>
    </div>

