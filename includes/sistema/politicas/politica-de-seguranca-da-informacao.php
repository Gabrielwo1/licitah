  <p>A <?=$nomeEmpresa?> está comprometida em proteger as informações e dados dos nossos usuários. Esta Política de Segurança da Informação descreve as diretrizes e práticas que seguimos para garantir a confidencialidade, integridade e disponibilidade das informações.</p>

    <h2>1. Objetivo</h2>
    <p>O objetivo desta política é estabelecer um conjunto de diretrizes para proteger a informação contra acesso não autorizado, divulgação, modificação e destruição.</p>

    <h2>2. Escopo</h2>
    <p>Esta política se aplica a todos os colaboradores, parceiros e prestadores de serviços que tenham acesso às informações da <?=$nomeEmpresa?>.</p>

    <h2>3. Responsabilidades</h2>
    <p>Todos os funcionários devem seguir as práticas de segurança estabelecidas nesta política. A equipe de TI é responsável pela implementação e monitoramento das medidas de segurança.</p>

    <h2>4. Proteção de Dados</h2>
    <p>Os dados pessoais dos usuários devem ser coletados, armazenados e processados de acordo com as leis de proteção de dados aplicáveis. Medidas de segurança, como criptografia e controle de acesso, devem ser utilizadas para proteger as informações.</p>

    <h2>5. Controle de Acesso</h2>
    <p>O acesso às informações sensíveis deve ser limitado aos usuários autorizados. Credenciais de acesso, como senhas, devem ser mantidas em segredo e trocadas regularmente.</p>

    <h2>6. Treinamento e Conscientização</h2>
    <p>Todos os funcionários devem receber treinamento regular sobre segurança da informação e as práticas recomendadas para proteger os dados da empresa.</p>

    <h2>7. Monitoramento e Auditoria</h2>
    <p>Medidas de monitoramento devem ser implementadas para identificar e responder a incidentes de segurança. Auditorias regulares serão conduzidas para garantir a conformidade com esta política.</p>

    <h2>8. Resposta a Incidentes</h2>
    <p>Em caso de violação de segurança, um plano de resposta a incidentes será acionado para minimizar o impacto e notificar os usuários afetados, se necessário.</p>

    <h2>9. Alterações a esta Política</h2>
    <p>A <?=$nomeEmpresa?> reserva-se o direito de atualizar esta Política de Segurança da Informação a qualquer momento. As alterações entrarão em vigor assim que forem publicadas nesta página.</p>

