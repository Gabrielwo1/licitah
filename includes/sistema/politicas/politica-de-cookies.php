  <p>Esta Política de Cookies explica o que são cookies e como os utilizamos, como terceiros com os quais podemos cooperar podem usar cookies em nosso site e suas escolhas em relação a cookies.</p>

    <h2>1. O que são cookies?</h2>
    <p>Cookies são pequenos arquivos de texto que são usados para armazenar informações. Eles são armazenados no seu dispositivo quando o site é carregado em seu navegador. Esses cookies ajudam o site a funcionar corretamente, tornam-o mais seguro, proporcionam melhores experiências para o usuário e analisam o desempenho do site.</p>

    <h2>2. Como usamos cookies</h2>
    <p>Ao utilizar nosso site, podemos usar cookies para:</p>
    <ul>
        <li>Reconhecer você como usuário quando retornar ao nosso site;</li>
        <li>Registrar suas preferências e configurações;</li>
        <li>Realizar análises e entender como nossos serviços são utilizados;</li>
        <li>Personalizar o conteúdo e os anúncios que você vê.</li>
    </ul>

    <h2>3. Tipos de cookies que utilizamos</h2>
    <p>Utilizamos os seguintes tipos de cookies:</p>
    <ul>
        <li><strong>Cookies essenciais:</strong> Necessários para o funcionamento do site.</li>
        <li><strong>Cookies de desempenho:</strong> Ajudam a entender como os visitantes interagem com o site.</li>
        <li><strong>Cookies de funcionalidade:</strong> Permitem ao site lembrar suas preferências e melhorar sua experiência.</li>
        <li><strong>Cookies de publicidade:</strong> Usados para exibir anúncios relevantes para você.</li>
    </ul>

    <h2>4. Cookies de terceiros</h2>
    <p>Além dos nossos próprios cookies, também podemos usar vários cookies de terceiros para relatar estatísticas de uso do site e entregar anúncios relevantes. Esses cookies são geridos por terceiros e estão sujeitos às respectivas políticas de privacidade.</p>

    <h2>5. Gerenciando cookies</h2>
    <p>Você tem o direito de decidir se aceita ou rejeita cookies. Você pode definir suas preferências de cookies em seu navegador. No entanto, se você optar por rejeitar cookies, pode não ser capaz de usar todas as funcionalidades do nosso site.</p>
    <p>Para gerenciar os cookies, você pode visitar as configurações do seu navegador. Aqui estão alguns links úteis para gerenciar cookies nos navegadores mais populares:</p>
